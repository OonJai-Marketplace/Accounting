import {mkdir,copyFile,readFile,writeFile} from 'node:fs/promises';
import {build} from 'esbuild';
await mkdir('www/vendor',{recursive:true});
for(const name of ['index.html','app.css'])await copyFile('src/'+name,'www/'+name);
await copyFile('../../scripts/receipt-core202.js','www/vendor/core.js');
await copyFile('../../assets/vendor/document14285/jspdf.umd.min.js','www/vendor/jspdf.js');
const pdf=(await readFile('../../scripts/receipt-pdf202.js','utf8')).replace('Oon Jai supporting documents','Supporting documents').replace('Oon Jai Accounting Scanner','Pocket Scan');
await writeFile('www/vendor/pdf.js',pdf);
await build({entryPoints:['src/app.mjs'],bundle:true,format:'iife',platform:'browser',target:['safari15','chrome90'],outfile:'www/app.js',sourcemap:false});
console.log('Bundled scanner, image correction, PDF and native adapters. No remote runtime assets.');
