const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync('src/bridges/subusers-bookkeeping/budget-workflow14316.js','utf8');
const ctx=vm.createContext({num:n=>Number(n)||0,report:{orderedUnits:codes=>[...codes].sort(),amountLines:(codes,value)=>codes.map(c=>c+' '+value(c).toFixed(2)).join('<br>')},table82:(labels)=>'<table><thead><tr>'+labels.map(label=>'<th>'+label+'</th>').join('')+'</tr></thead></table>'});
vm.runInContext(source.slice(source.indexOf('function utilizationHeaderTotals('),source.indexOf("function renderRequest(notice=")),ctx);
const a={balances:new Map([['USD',{requested:10.10,receipt:20,cashSpent:22,beforeReturn:-2,remaining:-7}],['LAK',{requested:1000,receipt:1500,cashSpent:1100,beforeReturn:400}]])};
const b={balances:new Map([['USD',{requested:20.20,receipt:30,cashSpent:15,beforeReturn:15}],['LAK',{requested:2000,receipt:3000,cashSpent:2500,beforeReturn:500}]])};
const snapshot=JSON.stringify([a,b],(_,v)=>v instanceof Map?[...v]:v);
const totals=ctx.utilizationHeaderTotals([a,b]);
assert.equal(totals.get('USD').requested,30.30);
assert.equal(totals.get('USD').receipt,50);
assert.equal(totals.get('USD').cashSpent,37);
assert.equal(totals.get('USD').beforeReturn,13,'Uses remaining before handover, like register rows');
assert.equal(totals.get('LAK').beforeReturn,900);
assert.equal(ctx.utilizationHeaderTotals([a]).get('USD').beforeReturn,-2,'Filtered totals include only visible reports and preserve negative balances');
assert.equal(ctx.utilizationHeaderTotals([]).size,0);
assert.equal(JSON.stringify([a,b],(_,v)=>v instanceof Map?[...v]:v),snapshot,'Totals never mutate financial records');
const html=ctx.utilizationRegister([a,b],[]);
assert.equal((html.match(/<th /g)||[]).length,8,'One ordinary header row retains column resizing');
assert.equal((html.match(/data-resize-label=/g)||[]).length,8,'Stable labels preserve widths when totals change');
assert.match(html,/aria-label="Total requested">LAK 3000.00<br>USD 30.30/);
assert.match(html,/Total · 2 reports/);
assert.match(ctx.utilizationRegister([],[]),/Total · 0 reports/);
assert.match(source,/utilizationRegister\(reports,utilization\)/);
assert.match(source,/const reports=rows\.filter/,'Both rows and totals use month-filtered reports');
console.log('PASS: currency-separated header totals, cent precision, negatives, filtering, empty results, stable column identities and immutable sources.');
