import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {loadSource,sourceRows,projections,batches} from '../integrations/google-sheets/refresh.mjs';
const hash=s=>createHash('sha256').update(s).digest('hex');
const days=Array.from({length:31},(_,i)=>({date:'2026-10-'+String(i+1).padStart(2,'0'),mark:'0'}));
const results=Array.from({length:6},(_,i)=>({employeeId:'e'+i,employee:{name:'E'+i},attendance95:days}));
const tables={payroll_runs:[JSON.stringify({id:'p',data:{month:'2026-10',results,rows:[]}})],sub_accounts:[JSON.stringify({id:'s',description:'A'.repeat(27900)+'😀'.repeat(500)})],journal_fx_evidence288:['{"entry_id":"j","source_amount":1.000000000000000001}']};
const inventory=Object.fromEntries(Object.entries(tables).map(([t,rows])=>[t,{count:rows.length,bytes:rows.join('').length,hash:hash(rows.map(hash).sort().join(''))}]));
const rpc=async(t,i,n)=>t?tables[t].slice(i,i+n):inventory;
const state=await loadSource(rpc,()=>{}),views=projections(state.tables,2026);
assert.equal(views.Attendance.length-1,186);
assert.equal(new Set(views.Attendance.slice(1).map(r=>r[2]+'/'+r[4])).size,186);
const a=sourceRows(state.tables,state.source,'one'),b=sourceRows(state.tables,state.source,'later');
assert.deepEqual(a.history.map(r=>r[0]),b.history.map(r=>r[0]));
assert.equal(a.raw.filter(r=>r[0]==='sub_accounts').map(r=>r[3]).join(''),tables.sub_accounts[0]);
assert.equal(a.raw.find(r=>r[0]==='journal_fx_evidence288')[3],tables.journal_fx_evidence288[0]);
const chunks=batches(a.raw,28000);assert.equal(chunks[0][0],0);assert.equal(chunks.at(-1)[1],a.raw.length);
await assert.rejects(loadSource(async(t,i,n)=>t==='journal_fx_evidence288'?['{"entry_id":"j","source_amount":2}']:rpc(t,i,n),()=>{}),/Accounting changed/);
console.log('PASS October employee-days, numeric precision, stable revision IDs, multipart Unicode records and change-during-read detection.');
